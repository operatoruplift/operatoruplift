// Builds README.md from the card sequence, so alt text and links never drift from the images.
// Usage: npm run readme   (check.mjs imports buildReadme() to detect a stale README)
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { SEQUENCE, pngName, variantsOf } from './cards/index.mjs';
import { RAW_BASE } from './content.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const README = path.join(ROOT, 'README.md');
const WIDTHS = { full: '100%', pair: '49%' };
const CHIP_HEIGHT = 44;
const HEADER = '<!-- Generated by src/readme.mjs. Edit src/content.mjs, then run: npm run build -->';

const attr = (s) => {
  if (s == null) throw new Error('Missing attribute value');
  return String(s).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
};

// GitHub proxies README images through a cache keyed on the full URL, so a content hash in
// the query string makes every re-render show up without renaming files.
function url(name) {
  const bytes = fs.readFileSync(path.join(ROOT, 'img', name));
  const hash = crypto.createHash('sha256').update(bytes).digest('hex').slice(0, 10);
  return `${RAW_BASE}${name}?v=${hash}`;
}

function image(card, size) {
  const alt = `alt="${attr(card.alt)}"`;
  const [light, dark] = variantsOf(card).map((theme) => url(pngName(card, theme)));
  if (!dark) return `<img src="${light}" ${alt} ${size}>`;
  return '<picture>'
    + `<source media="(prefers-color-scheme: dark)" srcset="${dark}">`
    + `<source media="(prefers-color-scheme: light)" srcset="${light}">`
    + `<img src="${light}" ${alt} ${size}>`
    + '</picture>';
}

const linked = (card, inner) => (card.link ? `<a href="${attr(card.link)}">${inner}</a>` : inner);

function block({ layout, cards }) {
  const size = layout === 'chips' ? `height="${CHIP_HEIGHT}"` : `width="${WIDTHS[layout]}"`;
  return ['<p align="center">', ...cards.map((card) => `  ${linked(card, image(card, size))}`), '</p>'].join('\n');
}

export const buildReadme = () => `${[HEADER, ...SEQUENCE.map(block)].join('\n\n')}\n`;

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const markdown = buildReadme();
  fs.writeFileSync(README, markdown);
  console.log(`README.md: ${SEQUENCE.length} blocks, ${Buffer.byteLength(markdown)} bytes`);
}
